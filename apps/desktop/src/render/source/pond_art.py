def hornwort(frame):
    cel = Cel(1,(116,112))
    rng = Random(40+frame)
    for stem, (end_x,end_y) in enumerate(((19,33),(32,21),(69,11),(91,27),(103,43),(46,9))):
        start=(51+stem*3,105)
        points=[]
        for step in range(13):
            t=step/12
            points.append((start[0]+(end_x-start[0])*t**1.8 + sin(t*4.1+stem)*5*t,
                           start[1]+(end_y-start[1])*t))
        cel.line("#2b5a47",3,*points)
        cel.line("#7ea562" if stem%3 else "#668e57",1,*points)
        for ix in range(3,12):
            x,y=points[ix]
            length=(7+sin(ix/12*pi)*7)*rng.uniform(.77,1.12)
            for side in (-1,1):
                ex=x+side*length
                ey=y-3-rng.randrange(1,6)
                cel.poly("#416e4b",(x-1,y+1),(x+side*4,y-2),(ex,ey),
                         (ex-side*4,ey+4),(x+side*4,y+1))
                cel.line("#7b9f5d",1,(x,y),(x+side*5,y-2),(ex,ey))
                if (ix+stem)%3==0:
                    cel.line("#a6b975",1,(ex-side*2,ey+1),(ex,ey))
                cel.line("#558a59",1,(x+side*2,y),(x+side*length*.63,y+3))
    return cel


