def blades(cel, x, y, height, spread, palette, seed):
    shade, face, tip = palette
    rng = Random(seed)
    for i in range(9):
        end_x=x+rng.uniform(-spread,spread)
        end_y=y-height*rng.uniform(.40,1)
        bow_x=x+(end_x-x)*.21+rng.uniform(-5,5)
        blade=rng.randrange(2,6)
        cel.poly(shade,(x-blade,y),(bow_x-blade,(y+end_y)*.56),(end_x,end_y),
                 (bow_x+blade,(y+end_y)*.55),(x+blade,y))
        cel.poly(face,(x-1,y-2),(bow_x-1,(y+end_y)*.56),(end_x,end_y),
                 (bow_x+blade*.65,(y+end_y)*.56),(x+2,y-4))
        if i%3==1:
            cel.line(tip,1,(bow_x,(y+end_y)*.56),(end_x,end_y))


