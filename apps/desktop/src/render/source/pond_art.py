def stone(cel, x, y, w, h, palette, seed):
    shadow, body, light, rim = palette

    def shape(tone, vertices):
        cel.poly(tone, *((x + dx * w, y + dy * h) for dx, dy in vertices))

    cel.oval((31,46,36,86),x-w*1.05,y-h*.19,w*2.10,h*.48)
    shape(shadow, ((-.99,.01),(-.87,-.44),(-.57,-.78),(-.21,-.92),(.06,-1),
                   (.50,-.87),(.82,-.52),(.94,-.1),(.68,.25),(.04,.32),(-.57,.24)))
    shape(body, ((-.95,-.05),(-.76,-.53),(-.53,-.78),(-.21,-.90),(.08,-.95),
                 (.50,-.81),(.75,-.52),(.66,-.22),(.37,-.08),(.07,-.20),(-.18,.04),(-.53,.09)))
    shape(light, ((-.80,-.28),(-.52,-.74),(-.22,-.87),(.08,-.92),(.48,-.77),
                   (.57,-.63),(.37,-.54),(.03,-.62),(-.19,-.52),(-.38,-.52),(-.56,-.35)))
    shape(rim, ((-.63,-.51),(-.48,-.75),(-.14,-.85),(.08,-.85),(.22,-.77),
                 (-.07,-.75),(-.25,-.71),(-.44,-.66)))
    shape(shadow, ((.58,-.57),(.80,-.51),(.87,-.23),(.70,-.02),(.47,.05),(.52,-.15),(.38,-.25)))
    rng = Random(seed)
    for index in range(round(5 + w / 5)):
        dx = rng.uniform(-.49,.47)
        dy = rng.uniform(-.6,-.15)
        cel.line(light if index % 3 else shadow,1,(x+dx*w,y+dy*h),
                 (x+dx*w+w*rng.uniform(.05,.21),y+dy*h-1))


