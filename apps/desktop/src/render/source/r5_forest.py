            (131, 130, ((103, 70), (143, 57), (180, 66)), ('#3d502d', '#587139', '#798a43'), 8),
            (372, 143, ((324, 56), (365, 37), (410, 32), (455, 68), (452, 95)), ('#344624', '#5a7140', '#81904b'), 12),
