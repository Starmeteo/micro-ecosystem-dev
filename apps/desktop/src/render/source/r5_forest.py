def woodlouse(pose):
    cel = Cel(1, (22, 15))
    if pose != 'hidden':
        for index in range(6):
            x = 6 + index * 2
            toe = 11 + (pose == 'walk' and index % 2 > 0)
            cel.line('#3d453a', 1, (x, 8), (x + (index % 3 - 1), 10), (x + 1, toe))
        cel.line('#858a79', 1, (5, 6), (3, 4), (1, 4))
        cel.line('#8b907f', 1, (5, 7), (3, 8), (1, 7))
    else:
        cel.line('#5b6256', 1, (5, 7), (3, 6), (2, 7))
    cel.poly('#29352f', (4, 6), (6, 4), (8, 3), (13, 3), (16, 4), (17, 6),
             (17, 8), (15, 10), (7, 10), (5, 9), (4, 8))
    tones = ('#697366', '#747e71', '#7f897b', '#859084', '#748174', '#6d776a', '#5b6b60')
    for index, tone in enumerate(tones):
        x = 6 + index * 1.5
        mid = 4 + int(index in (0, 6))
        cel.line(tone, 1, (x, mid), (x + 1, 7), (x, 9))
    cel.line('#a1a793', 1, (8, 4), (9, 3), (11, 3))
    cel.line('#929986', 1, (12, 3), (14, 4))
    cel.box('#454e43', 4, 7, 2, 2)
    return cel


def render_forest():
    light = Cel(1)
    for coords, color in ((((36, 183), (100, 183), (135, 171), (99, 174)), (176, 160, 97, 16)),
                          (((213, 211), (241, 210), (258, 198), (224, 204)), (194, 169, 95, 21)),
                          (((258, 219), (302, 234), (318, 230), (286, 217)), (198, 163, 96, 16))):
        light.poly(color, *coords)
    leaf = Cel(1, (76, 33))
    fallen_leaf(leaf, (10, 22), 55, 15, -.22, ('#64442d', '#9c673f', '#c28a50', '#aa7244'))
    large_leaf = Cel(1, (130, 70))
    fallen_leaf(large_leaf, (12, 28), 111, 32, .235, ('#4c2e25', '#78442e', '#966038', '#865031'))
    moss = Cel(1, (60, 25))
    moss_pad(moss, 30, 18, 43, 16, MOSS, 12)
    log, log_front, log_shadow, log_growth = forest_log()
    return {
        'clean-base': forest_base(), 'foreground': forest_foreground(), 'light': light,
        'rock': forest_rock(), 'rock-shadow': ellipse_shadow((64, 48), (32, 39), 59, 15, (25, 25, 20)),
        'log-back': log, 'log-front': log_front, 'log-shadow': log_shadow, 'log-growth': log_growth,
        'leaf': leaf, 'leaf-large': large_leaf, 'moss': moss,
        'woodlouse-idle': woodlouse('idle'), 'woodlouse-walk': woodlouse('walk'),
        'woodlouse-hidden': woodlouse('hidden'),
    }
