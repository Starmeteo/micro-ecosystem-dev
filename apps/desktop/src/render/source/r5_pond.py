def whorls(cel, x, y, height, bend, colors):
    dark, middle, rim = colors
    cel.line(dark, 2, (x, y), (x + bend * .29, y - height * .4), (x + bend * .47, y - height * .66),
             (x + bend, y - height))
    for index in range(1, 7):
        t = index / 7
        px = x + bend * (t ** 1.4)
        py = y - height * t
        size = (1 - t * .57) * (height * .18 + 2) * (.8 + .2 * sin(index * 1.3))
        for side in (-1, 1):
            tone = rim if (side == 1 and index % 2) else middle
            cel.line(tone, 1, (px, py), (px + side * size * .32, py - size * .34),
                     (px + side * size * .71, py - size * .42), (px + side * size, py - size * .15))
            cel.line(middle, 1, (px + side * size * .35, py - size * .33),
                     (px + side * size * .54, py - size * .65))
            cel.line(middle, 1, (px, py), (px + side * size * .36, py - size * .7))


